static TDD_DISP_QSPI_CFG_T sg_disp_qspi_cfg = {
    .cfg = {
        .refresh_method = QSPI_REFRESH_BY_FRAME,
        .cmd_opcode = ST77916_QSPI_WRITE_CMD,
        .pixel_cmd_1wire = {
            .cmd = ST77916_QSPI_WRITE_CMD,
            .cmd_lines = TUYA_QSPI_1WIRE,
            .addr = {0x00U, ST77916_QSPI_PIXEL_ADDR1, 0x00U},
            .addr_size = 3U,
            .addr_lines = TUYA_QSPI_1WIRE,
        },
        .pixel_cmd_4wire = {
            .cmd = ST77916_QSPI_WRITE_COLOR,
            .cmd_lines = TUYA_QSPI_1WIRE,
            .addr = {0x00U, ST77916_QSPI_PIXEL_ADDR1, 0x00U},
            .addr_size = 3U,
            .addr_lines = TUYA_QSPI_1WIRE,
        },
        .has_vram = true,
        .cmd_caset = ST77916_CASET,
        .cmd_raset = ST77916_RASET,
    },
    .init_seq = cST77916_PANEL_INIT_SEQ,
    .is_swap = true,
};

OPERATE_RET tdd_disp_qspi_st77916_set_init_seq(const uint8_t *init_seq)
{
    if (init_seq == NULL) {
        return OPRT_INVALID_PARM;
    }
    sg_disp_qspi_cfg.init_seq = init_seq;
    return OPRT_OK;
}

OPERATE_RET tdd_disp_qspi_st77916_register(char *name,
                                            DISP_QSPI_DEVICE_CFG_T *dev_cfg)
{
    PR_NOTICE("tdd_disp_qspi_st77916_register: %s", name ? name : "(null)");
    return tdd_disp_qspi_panel_register(name, &sg_disp_qspi_cfg, dev_cfg);
}
